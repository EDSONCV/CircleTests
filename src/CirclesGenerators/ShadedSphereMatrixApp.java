        int[][] cores = new int[n][3];
        double[][] paramsIluminacao = new double[n][];
        double[] amb = new double[n];

        Random random = new Random();

        // -------------------------------------------------------------
        // ESCOLHA O MODO AQUI PARA TESTAR
        // -------------------------------------------------------------
        int modoAtual = ShadedSphere.ILUM_DEGRADE_BORDA; // Troque para DIRECIONAL ou RING_LIGHT

        // Preenchendo as características
        for (int i = 0; i < n; i++) {
            cores[i][0] = random.nextInt(256); // R
            cores[i][1] = random.nextInt(256); // G
            cores[i][2] = random.nextInt(256); // B

            amb[i] = random.nextDouble() * 0.4; // Luz ambiente

            // Preenche os parâmetros da luz dependendo do modo escolhido
            if (modoAtual == ShadedSphere.ILUM_DIRECIONAL) {
                double lx = (random.nextDouble() * 2.0) - 1.0;
                double ly = (random.nextDouble() * 2.0) - 1.0;
                double lz = (random.nextDouble() * 2.0) - 1.0;
                if (lx == 0 && ly == 0 && lz == 0) lx = 1.0;
                paramsIluminacao[i] = new double[]{lx, ly, lz};

            } else if (modoAtual == ShadedSphere.ILUM_RING_LIGHT) {
                // Raio do anel entre 0.6 e 0.9 | Largura entre 0.05 e 0.2
                double raioAnel = 0.6 + (random.nextDouble() * 0.3);
                double largura = 0.05 + (random.nextDouble() * 0.15);
                paramsIluminacao[i] = new double[]{raioAnel, largura};

            } else if (modoAtual == ShadedSphere.ILUM_DEGRADE_BORDA) {
                // Fator de decaimento entre 1.5 e 4.0
                double decaimento = 1.5 + (random.nextDouble() * 2.5);
                paramsIluminacao[i] = new double[]{decaimento};
            }
        }

        // 4. Criação do Gerador usando o modoAtual
        ShadedSphereMatrixGenerator generator = new ShadedSphereMatrixGenerator(
                modoAtual, raios, cores, paramsIluminacao, amb, 15, false);

        // 5. Gera a Imagem
        Mat imagemGerada = generator.generate();

        // 6. Mostra no Visualizador
        SwingUtilities.invokeLater(() -> {
            new SphereMatrixViewer(imagemGerada);
        });
